"""Regenerate the STATUS:GENERATED block of CLAUDE.md from real truth anchors.

The block says "auto-block, re-generated by sf-sm-doctor", but the auditor
only READS: it has no write mode. The real generator is this script.

Every number in the block comes from a command that is listed in the
"SFuente (Truth Anchor)" column, so the block can be re-measured at any
time instead of being edited by hand.

Which tree is measured
----------------------
The tree comes from ``VH_WT`` (default: the current branch's worktree).
The size of the shipped ``.exe`` is read from the RELEASE worktree
(``bloquec-67-goliath-port``), because a worktree in progress has no
``dist/``: measuring it from there would report 0 MB.

Usage:
    python tools/regen_status.py
    VH_WT=F:\\AI\\MM\\void-hunter\\.worktrees\\bloquec-67-goliath-port python tools/regen_status.py
"""
from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path

ROOT = Path(
    os.environ.get(
        "VH_WT",
        r"F:\AI\MM\void-hunter\.worktrees\bloquec-75-sprite-migration",
    )
)
RELEASE_WT = ROOT.parent / "bloquec-67-goliath-port"
RELEASE_BRANCH = "bloquec-67-goliath-port"
PY = r"F:\AI\MM\void-hunter\.venv\Scripts\python.exe"
CLAUDE = ROOT / "CLAUDE.md"


def run(cmd: list[str], cwd: Path = ROOT) -> str:
    proc = subprocess.run(
        cmd,
        cwd=str(cwd),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    return proc.stdout.strip()


def loc(folder: str) -> str:
    """Lines of code under `folder`."""
    code = (
        "import pathlib; print(sum(len(p.read_text(encoding='utf-8',errors='ignore').splitlines()) "
        f"for p in pathlib.Path('{folder}').rglob('*.py')))"
    )
    return run([PY, "-c", code])


def pyfiles(folder: str) -> int:
    """Number of .py files under `folder`."""
    out = run(
        [
            "powershell",
            "-NoProfile",
            "-Command",
            f"(Get-ChildItem -Recurse -Filter *.py '{folder}' | Measure-Object).Count",
        ]
    )
    return int(out)


def main() -> int:
    text = CLAUDE.read_text(encoding="utf-8")

    src_loc = loc("src")
    tests_loc = loc("tests")
    src_files = pyfiles("src")
    n_silos = len([p for p in (ROOT / "docs").iterdir() if p.is_dir()])

    exe = RELEASE_WT / "dist" / "void-hunter.exe"
    exe_mb = round(exe.stat().st_size / 1024 / 1024, 1) if exe.is_file() else 0

    branch = run(["git", "branch", "--show-current"])
    if branch != RELEASE_BRANCH:
        # The block is a Spanish document: the value stays in Spanish.
        branch = (
            f"{branch} (en curso; la línea de release es {RELEASE_BRANCH})"
        )

    pytest = subprocess.run(
        [PY, "-m", "pytest", "tests/", "--tb=no"],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    tail = pytest.stdout.strip().splitlines()[-1]
    match = re.search(r"(\d+) failed, (\d+) passed, (\d+) skipped", tail)
    if not match:
        print(f"could not read the pytest summary: {tail}")
        return 1
    failed, passed, skipped = (
        int(match.group(1)),
        int(match.group(2)),
        int(match.group(3)),
    )
    total = failed + passed + skipped

    print(f"src LOC={src_loc} files={src_files} | tests LOC={tests_loc}")
    print(f"suite: {passed} pass / {failed} fail / {skipped} skipped ({total})")
    print(f"silos={n_silos} exe={exe_mb}MB branch={branch}")

    rows = {
        "Líneas de código (src/)": f"{src_loc}",
        "Archivos Python (src/)": f"{src_files}",
        "Tests (tests/)": (
            f"{passed:,} pass + {failed} fail pre-existente + {skipped} skipped "
            f"({total:,} total)"
        ).replace(",", "."),
        "LOC tests/": f"{tests_loc}",
        "Silos SF+SM": f"{n_silos} (Lite)",
        "Rama": branch,
        "Build .exe": (
            f"**reconstruido** para v1.8.0 ({exe_mb} MB) en `dist/void-hunter.exe` "
            "— el path congelado (`<_MEIPASS>/Assets/sprites/bosses`) verificado con "
            "el manifest y los anchors dentro del bundle"
        ),
    }

    out: list[str] = []
    changed = 0
    for line in text.splitlines():
        row = re.match(r"^\| ([^|]+?) \| (.*?) \| (.*?) \|$", line)
        if row and row.group(1).strip() in rows:
            key = row.group(1).strip()
            line = f"| {key} | {rows[key]} | {row.group(3)} |"
            changed += 1
        out.append(line)

    CLAUDE.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"rows updated: {changed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
