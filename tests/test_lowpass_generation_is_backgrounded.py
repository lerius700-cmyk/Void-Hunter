# ---------------------------------------------------------------------------
# 2. The copy joins IN SYNC.
# ---------------------------------------------------------------------------
def test_the_copy_joins_the_bgm_at_the_position_the_song_is_at(monkeypatch) -> None:
    """The two copies have to stay ALIGNED.

    The filtered copy starts at the position the song is AT, not at
    zero: they are the same song, and the pause is a volume swap
    between them. Starting the filtered at zero would make the swap
    jump the song back to the beginning.
    """
    bgm, filtered = _fake_channels()
    sound = _FakeSound("track.wav", length=300.0)
    monkeypatch.setattr(music, "_ensure_mixer", lambda: True)
    monkeypatch.setattr(music, "_find_track", lambda name: Path("track.wav"))
    monkeypatch.setattr(music, "_load_sound", lambda p: sound)
    monkeypatch.setattr(music, "_filtered_cache_lookup", lambda: "filtered.wav")
    music._original_sound = sound
    music._filtered_sound = None
    music._filtered_in_sync = False
    music._filtered_ready_path = "filtered.wav"
    music._bgm_started_at = time.monotonic() - 42.0
    bgm.busy = True

    music.update()

    plays = [c for c in filtered.calls if c[0] == "play"]
    assert len(plays) == 1, f"the filtered channel did not join: {filtered.calls}"
    _kind, _snd, _loops, start = plays[0]
    assert start == pytest.approx(42.0, abs=1.0), (
        f"the copy joined at {start}s, not at the 42s the song is at"
    )


def test_the_copy_joins_only_once(monkeypatch) -> None:
    """Once it is in sync, the per-frame hook does nothing.

    The hook runs EVERY FRAME: re-starting the channel every frame
    would restart the song every frame.
    """
    bgm, filtered = _fake_channels()
    sound = _FakeSound("track.wav", length=300.0)
    monkeypatch.setattr(music, "_load_sound", lambda p: sound)
    music._original_sound = sound
    music._filtered_sound = None
    music._filtered_in_sync = False
    music._filtered_ready_path = "filtered.wav"
    music._bgm_started_at = time.monotonic() - 10.0
    bgm.busy = True

    music.update()
    music.update()
    music.update()

    plays = [c for c in filtered.calls if c[0] == "play"]
    assert len(plays) == 1, f"the copy joined {len(plays)} times"


def test_nothing_joins_when_the_copy_is_not_ready(monkeypatch) -> None:
    """The hook does not start a channel with nothing on it."""
    bgm, filtered = _fake_channels()
    monkeypatch.setattr(music, "_filtered_cache_lookup", lambda: None)
    music._filtered_ready_path = None
    music._filtered_in_sync = False

    music.update()

    assert [c for c in filtered.calls if c[0] == "play"] == []


# ---------------------------------------------------------------------------
# 3. A pause without the copy is a no-op, not silence.
# ---------------------------------------------------------------------------
def test_the_pause_without_the_copy_is_a_no_op(monkeypatch) -> None:
    """Muting the BGM and unmuting an EMPTY channel would be silence.

    Silence is worse than an unfiltered pause: the pause has to leave
    the music playing.
    """
    bgm, filtered = _fake_channels()
    bgm.busy = True
    filtered.busy = False  # the copy has not joined
    monkeypatch.setattr(music, "_ensure_mixer", lambda: True)
    monkeypatch.setattr(music, "get_current_track", lambda: "gameplay")
    music._is_paused = False

    assert music.enter_pause_lowpass() is False
    # the BGM was NOT muted: the music keeps playing
    assert not any(
        c[0] == "set_volume" and c[1] == 0.0 for c in bgm.calls
    ), f"the BGM was muted with no filtered copy to replace it: {bgm.calls}"
    assert music._is_paused is False


def test_the_pause_with_the_copy_swaps_the_volumes(monkeypatch) -> None:
    """The effect itself is unchanged once the copy has joined."""
    bgm, filtered = _fake_channels()
    bgm.busy = True
    filtered.busy = True
    monkeypatch.setattr(music, "_ensure_mixer", lambda: True)
    monkeypatch.setattr(music, "get_current_track", lambda: "gameplay")
    music._is_paused = False

    assert music.enter_pause_lowpass() is True
    assert any(c[0] == "set_volume" and c[1] == 0.0 for c in bgm.calls)
    assert any(c[0] == "set_volume" and c[1] > 0.5 for c in filtered.calls)


# ---------------------------------------------------------------------------
# 4. With the copy already on disk, nothing changes.
# ---------------------------------------------------------------------------
def test_with_the_copy_cached_both_channels_start_together(monkeypatch) -> None:
    """The second run of the game: the copy is there, both channels start.

    This is the path that existed before, and it has to keep working:
    the copy is cached next to the executable, so the second launch
    pays nothing.
    """
    bgm, filtered = _fake_channels()
    sound = _FakeSound("track.wav", length=300.0)
    monkeypatch.setattr(music, "_ensure_mixer", lambda: True)
    monkeypatch.setattr(music, "_find_track", lambda name: Path("track.wav"))
    monkeypatch.setattr(music, "_load_sound", lambda p: sound)
    monkeypatch.setattr(music, "_filtered_cache_lookup", lambda: "filtered.wav")
    monkeypatch.setattr(
        music.pygame.mixer, "Channel", lambda index: bgm if index == 2 else filtered
    )
    music._current_track = None

    assert music.play_gameplay_music(force=True) is True
    assert bgm.busy is True
    assert filtered.busy is True, "the cached copy did not start"
    bgm_plays = [c for c in bgm.calls if c[0] == "play"]
    filt_plays = [c for c in filtered.calls if c[0] == "play"]
    assert bgm_plays and filt_plays
    # both start at zero, in sync
    assert bgm_plays[0][3] == 0.0
    assert filt_plays[0][3] == 0.0
    # and no worker was needed
    assert music._filtered_thread is None or not music._filtered_thread.is_alive()


def test_the_lookup_never_generates(monkeypatch) -> None:
    """The main thread's lookup is a LOOKUP.

    If it generated, the freeze would be back -- and it would be in the
    place nobody thinks to look: a function whose name says "lookup".
    """
    def _boom() -> str:
        raise AssertionError("the lookup generated the copy")

    monkeypatch.setattr(music, "_ensure_filtered_bgm", _boom)
    music._pause_filter_cache["filtered_path"] = None
    # The lookup must not raise, whatever it finds.
    music._filtered_cache_lookup()
