"""BLOQUE 76: the lowpass copy is generated in the BACKGROUND.

The filtered copy of the gameplay BGM is a 6,18 second pure-Python IIR
loop over a 91 MB WAV (measured on this machine). BLOQUE 75 moved the
copy out of the bundle and into runtime, which traded 63,9 MB of
download for a SIX-SECOND FREEZE at the TITLE -> GAMEPLAY transition --
and for six seconds again on EVERY session when the folder of the .exe
is not writable, because the fallback writes into the temporary bundle
that is wiped on exit.

Now the copy is generated by a worker thread and joins the BGM when it
is ready. The frame is never frozen.

These tests hold the three things that matter:

  1. the main thread does NOT generate (it returns immediately);
  2. the copy joins the BGM IN SYNC (at the position the song is at,
     not at zero -- the two have to stay aligned or the pause swap
     would be audible as the song jumping);
  3. a pause WITHOUT the copy is a no-op, not silence.

The channels are fakes: the tests must not depend on the machine having
an audio device.
"""
from __future__ import annotations

import os
import threading
import time
from pathlib import Path
from unittest import mock

os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
os.environ.setdefault("SDL_AUDIODRIVER", "dummy")

import pytest  # noqa: E402

from src.audio import music  # noqa: E402


class _FakeSound:
    """A Sound that records what it was asked to do."""

    def __init__(self, path: str = "fake.wav", length: float = 300.0) -> None:
        self.path = path
        self._length = length

    def get_length(self) -> float:
        return self._length


class _FakeChannel:
    """A Channel that records its calls."""

    def __init__(self) -> None:
        self.calls: list[tuple] = []
        self.busy = False
        self.volume = 1.0

    def play(self, sound, loops=0, start=0) -> None:
        self.calls.append(("play", sound, loops, start))
        self.busy = True

    def stop(self) -> None:
        self.calls.append(("stop",))
        self.busy = False

    def set_volume(self, volume) -> None:
        self.calls.append(("set_volume", volume))
        self.volume = volume

    def get_busy(self) -> bool:
        return self.busy


@pytest.fixture(autouse=True)
def _restore_music_state():
    """The music module keeps its state in module-level globals.

    A test that changes them must not change them for the rest of the
    suite: the next test would find a filtered channel already playing,
    or a worker thread still running.
    """
    saved = {
        "_bgm_channel": music._bgm_channel,
        "_filtered_channel": music._filtered_channel,
        "_original_sound": music._original_sound,
        "_filtered_sound": music._filtered_sound,
        "_current_track": music._current_track,
        "_is_paused": music._is_paused,
        "_filtered_thread": music._filtered_thread,
        "_filtered_ready_path": music._filtered_ready_path,
        "_filtered_in_sync": music._filtered_in_sync,
        "_bgm_started_at": music._bgm_started_at,
    }
    cache_before = dict(music._pause_filter_cache)
    yield
    thread = music._filtered_thread
    if thread is not None and thread.is_alive():
        thread.join(timeout=10.0)
    for name, value in saved.items():
        setattr(music, name, value)
    music._pause_filter_cache.clear()
    music._pause_filter_cache.update(cache_before)


def _fake_channels() -> tuple[_FakeChannel, _FakeChannel]:
    bgm = _FakeChannel()
    filtered = _FakeChannel()
    music._bgm_channel = bgm
    music._filtered_channel = filtered
    return bgm, filtered


# ---------------------------------------------------------------------------
# 1. The main thread does not generate.
# ---------------------------------------------------------------------------
def test_the_music_starts_without_waiting_for_the_filter(monkeypatch) -> None:
    """The copy is missing: the music starts NOW and the copy joins later.

    The generation is the slow part (6,18 s measured). If the main
    thread called it, this call would take that long -- which is the
    freeze the user would feel at the TITLE -> GAMEPLAY transition.
    """
    bgm, filtered = _fake_channels()
    generated = threading.Event()

    def _slow_generation() -> str:
        generated.set()
        time.sleep(1.5)
        return "filtered.wav"

    monkeypatch.setattr(music, "_ensure_mixer", lambda: True)
    monkeypatch.setattr(music, "_find_track", lambda name: Path("track.wav"))
    monkeypatch.setattr(music, "_load_sound", lambda p: _FakeSound(str(p)))
    monkeypatch.setattr(music, "_filtered_cache_lookup", lambda: None)
    monkeypatch.setattr(music, "_ensure_filtered_bgm", _slow_generation)
    monkeypatch.setattr(
        music.pygame.mixer, "Channel", lambda index: bgm if index == 2 else filtered
    )
    music._current_track = None

    t0 = time.monotonic()
    ok = music.play_gameplay_music(force=True)
    elapsed = time.monotonic() - t0

    assert ok is True, "the music must start even without the filtered copy"
    assert elapsed < 0.5, (
        f"play_gameplay_music took {elapsed:.2f}s: the generation ran on "
        "the main thread"
    )
    assert generated.wait(timeout=5.0), "the worker never started"
    # the BGM is playing; the filtered channel is not (nothing to play yet)
    assert bgm.busy is True
    assert filtered.busy is False


def test_the_generation_runs_on_a_worker_thread(monkeypatch) -> None:
    """The worker is a thread, and it is a daemon.

    A daemon never keeps the process alive: the game can close while
    the filter is still running.
    """
    bgm, filtered = _fake_channels()
    where: dict[str, str] = {}

    def _where_am_i() -> str:
        return threading.current_thread().name

    def _generation() -> str:
        where["thread"] = _where_am_i()
        return "filtered.wav"

    monkeypatch.setattr(music, "_ensure_mixer", lambda: True)
    monkeypatch.setattr(music, "_find_track", lambda name: Path("track.wav"))
    monkeypatch.setattr(music, "_load_sound", lambda p: _FakeSound(str(p)))
    monkeypatch.setattr(music, "_filtered_cache_lookup", lambda: None)
    monkeypatch.setattr(music, "_ensure_filtered_bgm", _generation)
    monkeypatch.setattr(
        music.pygame.mixer, "Channel", lambda index: bgm if index == 2 else filtered
    )
    music._current_track = None

    music.play_gameplay_music(force=True)
    thread = music._filtered_thread
    assert thread is not None, "no worker was started"
    assert thread.daemon is True, "the worker must not keep the process alive"
    thread.join(timeout=5.0)
    assert where.get("thread") == thread.name, (
        f"the generation ran on {where.get('thread')!r}, not on the worker"
    )


