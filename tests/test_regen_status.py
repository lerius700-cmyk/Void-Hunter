"""BLOQUE 75: `tools/regen_status.py` has to be trustworthy.

The STATUS block of CLAUDE.md is written by this tool. Two things about
it are load-bearing:

1. **It must write to the tree it lives in.** The repository is worked
   on by more than one agent, each in its own worktree. A generator
   that writes to a HARDCODED worktree edits a sibling agent's
   `CLAUDE.md` and leaves that agent with a stale one -- silently, with
   no error.
2. **It must not die when the suite changes shape.** The summary line of
   pytest is not a fixed string: "9 passed in 0.18s" when everything is
   green, "1 failed, 11 passed in 0.22s" when there are no skips, and
   the order of the counts varies. A parser that demands one exact
   shape stops the block from being regenerated the day the
   pre-existing failure is fixed -- which is the whole rot this tool
   exists to prevent.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import regen_status  # noqa: E402


def test_the_generator_targets_the_tree_it_lives_in():
    """ROOT is derived from the file's own location, not hardcoded.

    The agent working in `.worktrees\\bloquec-75-migration-spec` runs
    the tool that lives in ITS tree, and that tool must edit ITS
    `CLAUDE.md`.
    """
    tool = Path(regen_status.__file__).resolve()
    assert regen_status.ROOT == tool.parent.parent, (
        f"the generator measures and writes {regen_status.ROOT}, but it "
        f"lives in {tool.parent.parent}"
    )


def test_the_repository_root_is_derived_from_the_worktree():
    """A worktree's repository root is two levels up, not one."""
    assert regen_status.REPO_ROOT == ROOT.parent.parent or (
        regen_status.REPO_ROOT == ROOT
    )


@pytest.mark.parametrize(
    "tail,expected",
    [
        ("1 failed, 2908 passed, 6 skipped in 59.62s (0:01:00)", (1, 2908, 6)),
        ("9 passed in 0.18s", (0, 9, 0)),
        ("1 failed, 11 passed in 0.22s", (1, 11, 0)),
        ("6 skipped, 2908 passed in 1.00s", (0, 2908, 6)),
        ("2908 passed, 6 skipped in 1.00s", (0, 2908, 6)),
        (
            "2 failed, 2906 passed, 6 skipped, 1 warning in 62.14s (0:01:02)",
            (2, 2906, 6),
        ),
    ],
)
def test_every_shape_of_the_pytest_summary_is_parsed(tail: str, expected):
    """The counts are read one by one, not from one fixed sentence."""
    assert regen_status.parse_pytest_summary(tail) == expected


def test_the_parser_reads_the_counts_of_a_green_suite():
    """A green suite is the shape the parser must not choke on."""
    assert regen_status.parse_pytest_summary("9 passed in 0.18s") == (0, 9, 0)


def test_the_parser_reads_the_counts_of_a_suite_without_skips():
    """No skips, one failure."""
    assert regen_status.parse_pytest_summary("1 failed, 11 passed in 0.22s") == (
        1,
        11,
        0,
    )


def test_the_failing_tests_are_named():
    """The failing test ids are extracted, not just their number.

    The block says whether the failures are the known pre-existing ones.
    That claim needs the NAMES: a number alone cannot tell a known
    failure from a new one.
    """
    output = (
        "=================== short test summary info ===================\n"
        "FAILED tests/test_paths.py::test_paths_no_star_shapes - AssertionError: Lissa\n"
        "FAILED tests/test_other.py::test_new - AssertionError: boom\n"
        "1 failed, 2908 passed, 6 skipped in 59.62s\n"
    )
    failures = regen_status.parse_pytest_failures(output)
    assert failures == [
        "tests/test_paths.py::test_paths_no_star_shapes",
        "tests/test_other.py::test_new",
    ]


def test_the_block_header_names_the_generator_that_writes_it():
    """The header must not credit a tool that only reads.

    `sf-sm-doctor` audits the structure; it has no write mode. The block
    says it is auto-generated, and the honest name of the generator is
    `tools/regen_status.py`.
    """
    text = (ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    marker = text.index("STATUS:GENERATED")
    header = text[max(0, marker - 400) : marker + 400]
    assert "Re-generated by sf-sm-doctor" not in header, (
        "the block still claims sf-sm-doctor writes it: that tool only reads"
    )
    assert "regen_status.py" in header, (
        "the block does not name the tool that actually writes it"
    )
